  const DICTS = { en, es };
  const LOCALES = { en: 'en-US', es: 'es-ES' };
  let lang = 'en';

  function setLanguage(l) {
    lang = DICTS[l] ? l : 'en';
  }
  function getLanguage() {
    return lang;
  }
  function locale() {
    return LOCALES[lang];
  }
  function t(key, params = {}) {
    const d = DICTS[lang];
    let k = key;
    if (params.n !== undefined && (d[`${key}_one`] || en[`${key}_one`])) k = `${key}_${Number(params.n) === 1 ? 'one' : 'other'}`;
    let s = d[k] ?? en[k] ?? key;
    return s.replace(/\{(\w+)\}/g, (all, name) => {
      const v = params[name];
      if (v === undefined || v === null) return all;
      return typeof v === 'number' ? v.toLocaleString(LOCALES[lang], { useGrouping: 'always' }) : String(v);
    });
  }
  // Messages from the file readers: { code, detail }.
  function message(m) {
    if (!m) return t('readFailed');
    if (typeof m === 'string') return m;
    return t(`${m.kind === 'warn' ? 'warn' : 'err'}.${m.code}`, m);
  }

  return { t, setLanguage, getLanguage, locale, message, DICTS };
